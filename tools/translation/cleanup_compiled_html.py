def katakana_to_hiragana(text: str) -> str:
    chars: list[str] = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            chars.append(chr(code - 0x60))
        else:
            chars.append(ch)
    return "".join(chars)


def romanize_kana_sequence(match: re.Match[str]) -> str:
    text = katakana_to_hiragana(match.group(0))
    result: list[str] = []
    geminate = False
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == "っ":
            geminate = True
            i += 1
            continue
        if ch == "ー":
            if result:
                for last in reversed(result[-1]):
                    if last in "aeiou":
                        result.append(last)
                        break
            i += 1
            continue
        if i + 1 < len(text):
            pair = text[i:i + 2]
            if pair in ROMAJI_DIGRAPHS:
                romaji = ROMAJI_DIGRAPHS[pair]
                if geminate and romaji:
                    romaji = romaji[0] + romaji
                    geminate = False
                result.append(romaji)
                i += 2
                continue
        romaji = ROMAJI_MONOGRAPHS.get(ch, "")
        if not romaji:
            i += 1
            geminate = False
            continue
        if geminate and romaji:
            romaji = romaji[0] + romaji
            geminate = False
        result.append(romaji)
        i += 1
    return "".join(result)



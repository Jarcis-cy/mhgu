def main() -> None:
    changed = 0
    files = resolve_input_files(sys.argv[1:])
    for path in files:
        original = path.read_text(encoding="utf-8-sig")
        updated = cleanup_text(original)
        if updated != original:
            path.write_text(updated, encoding="utf-8")
            changed += 1
    print(f"updated {changed} html files")


if __name__ == "__main__":
    main()

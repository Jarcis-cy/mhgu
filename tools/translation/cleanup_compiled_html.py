def iter_html_files() -> list[Path]:
    files: list[Path] = []
    for dirname in HTML_DIRS:
        files.extend(sorted((HTML_ROOT / dirname).glob("*.html")))
    return files


def resolve_input_files(argv: list[str]) -> list[Path]:
    if not argv:
        return iter_html_files()

    files: list[Path] = []
    for raw_path in argv:
        path = Path(raw_path)
        if not path.is_absolute():
            path = ROOT / path
        files.append(path)
    return files


def localize_subject(text: str) -> str:
    localized = text
    for source, target in SUBJECT_REPLACEMENTS:
        localized = localized.replace(source, target)
    return localized


def localize_title_like_text(text: str) -> str:
    localized = text
    for source, target in TITLE_TEXT_REPLACEMENTS:
        localized = localized.replace(source, target)
    for source, target in TITLE_TOKEN_REPLACEMENTS:
        localized = localized.replace(source, target)
    return localized


def replace_title_tag(match: re.Match[str]) -> str:
    return f"{match.group('open')}{localize_title_like_text(match.group('text'))}{match.group('close')}"


def replace_reward_clause(match: re.Match[str]) -> str:
    subject = localize_subject(match.group("subject")).strip()
    count = "一次" if match.group("count") == "1" else "两次"
    return f"将{subject}的耐久值降为 0 {count}时的报酬"


def replace_plain_reward_clause(match: re.Match[str]) -> str:
    count = "一次" if match.group("count") == "1" else "两次"
    return f"将耐久值降为 0 {count}时的报酬"


def replace_multi_stage_clause(match: re.Match[str]) -> str:
    stage1 = localize_subject(match.group("stage1")).strip()
    stage2 = localize_subject(match.group("stage2")).strip()
    return f"分两阶段破坏时的报酬。第1阶段会{stage1}，第2阶段会{stage2}"


def replace_subject_zero_clause(match: re.Match[str]) -> str:
    subject = localize_subject(match.group("subject")).strip()
    count_map = {"2": "两次", "3": "三次", "5": "五次"}
    return f"将{subject}的耐久值降为 0 {count_map[match.group('count')]}"


def replace_certificate_clause(match: re.Match[str]) -> str:
    monster = match.group("monster").strip()
    return f"{monster}后获赠的证明券。先收集起来准没错！？"


def replace_fragment_material_clause(match: re.Match[str]) -> str:
    prefix_map = {
        "小さく欠けた": "小块缺损的",
        "欠けた上质之": "缺损的上等",
        "欠けた良质之": "缺损的优质",
        "欠けた极上之": "缺损的极品",
        "欠けた狞猛之": "缺损的狞猛之",
        "欠けた良质で狞猛之": "缺损的优质狞猛之",
    }
    prefix = prefix_map[match.group("prefix")]
    name = match.group("name").strip()
    return f"{prefix}{name}素材。形状并不规整，但收集起来后可以制作随从猫装备。"


